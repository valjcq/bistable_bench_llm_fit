"""POST-HOC analysis of existing results: "algorithm-selection headroom" (no new runs).

For each model, how much would an oracle that picks the best configuration PER TASK gain over
the one best configuration overall?
  SBS (Single Best Solver)  the configuration with the highest mean success over the model's tasks
  VBS (Virtual Best Solver) per task, the best configuration's success
  gap = mean VBS - mean SBS
Data (existing runs only, submission rule, success = submitted parameters pass the final check):
  toy      results/phase0/toy_grid_sr.csv   budget 200, 5 tasks x 5 seeds. C = expert_v2 (the file's
           C2 columns); the file's v1 columns are not used. A there was ranked by expert_v1.
  ei_2pop  results/ei_test/test.csv         budget 500, 9 tasks x 5 seeds
  wc1972   results/wc_selection/sel_200.csv budget 200, 5 selection tasks x 3 seeds (no TPE runs)
Two gap versions, because 3-5 seeds per cell make a per-task "best" noisy:
  plain         VBS = the maximum success rate over configurations on each task
  conservative  a configuration other than the SBS only counts on a task if it beats the SBS by
                MORE THAN ONE SEED (> 1 / n_seeds); otherwise the task is credited to the SBS
(Plain ties with the SBS already give no gap; the conservative version also discards 1-seed wins.)

    python scripts/selection_headroom.py       # writes results/selection_headroom.md
"""

from __future__ import annotations

import collections
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = {
    "toy_1pop (budget 200)": ("results/phase0/toy_grid_sr.csv", {"C2-cma": "C-cma", "C2-tpe": "C-tpe"}),
    "ei_2pop (budget 500)": ("results/ei_test/test.csv", {}),
    "wc1972 selection set (budget 200, 3 seeds)": ("results/wc_selection/sel_200.csv", {}),
}  # fmt: skip
ORDER = ["A", "B-cma", "B-tpe", "C-cma", "C-tpe"]


def load(path: str, rename: dict[str, str]):
    """success rate per (task, configuration), number of seeds per cell."""
    cells: dict[tuple[str, str], list[bool]] = collections.defaultdict(list)
    for r in csv.DictReader(open(ROOT / path)):
        label = rename.get(r["label"], r["label"])
        if label in ("C-cma", "C-tpe") and r["label"] == label and rename:
            continue  # toy file: its plain C columns are expert_v1, not used
        cells[(r["task_id"], label)].append(r["success"] == "True")
    tasks = sorted({t for t, _ in cells})
    configs = [c for c in ORDER if any((t, c) in cells for t in tasks)]
    rate = {k: sum(v) / len(v) for k, v in cells.items()}
    n_seeds = {k: len(v) for k, v in cells.items()}
    return tasks, configs, rate, n_seeds


def main() -> str:
    lines = [
        "# Algorithm-selection headroom (POST-HOC analysis of existing data)",
        "",
        "**Post-hoc analysis of results that already exist; no new runs and nothing was "
        "pre-registered.** Generated by `scripts/selection_headroom.py`. Definitions and the two gap "
        "versions are in the script docstring; the data sources are listed under each model.",
        "",
        'Caveat: each (task, configuration) cell is 3 to 5 seeds, so a per-task "best '
        'configuration" is noisy and the VBS is optimistically biased (a maximum over noisy '
        "estimates). The *conservative* column credits a non-SBS configuration only when it beats "
        "the SBS by more than one seed.",
    ]
    summary = []
    pooled = collections.defaultdict(list)
    for model, (path, rename) in SOURCES.items():
        tasks, configs, rate, n_seeds = load(path, rename)
        mean = {c: sum(rate[(t, c)] for t in tasks) / len(tasks) for c in configs}
        sbs = max(configs, key=lambda c: (mean[c], -configs.index(c)))  # ties: earlier in ORDER
        vbs_plain, vbs_cons, not_best = [], [], []
        for t in tasks:
            best = max(rate[(t, c)] for c in configs)
            vbs_plain.append(best)
            margin = 1 / n_seeds[(t, sbs)]
            others = [
                c for c in configs if c != sbs and rate[(t, c)] > rate[(t, sbs)] + margin + 1e-9
            ]
            vbs_cons.append(max([rate[(t, sbs)]] + [rate[(t, c)] for c in others]))
            if best > rate[(t, sbs)] + 1e-9:
                winners = [c for c in configs if rate[(t, c)] == best]
                not_best.append((t, rate[(t, sbs)], best, winners, bool(others)))
        m_sbs = mean[sbs]
        m_plain = sum(vbs_plain) / len(tasks)
        m_cons = sum(vbs_cons) / len(tasks)
        lines += [
            "",
            f"## {model}",
            "",
            f"Source: `{path}`; {len(tasks)} tasks, {max(n_seeds.values())}"
            f" seeds per cell. Mean success per configuration: "
            + ", ".join(f"{c} {mean[c]:.3f}" for c in configs)
            + f". **SBS = {sbs}.**",
            "",
        ]
        lines.append(
            "| task | "
            + " | ".join(f"{c}{' (SBS)' if c == sbs else ''}" for c in configs)
            + " | VBS |"
        )
        lines.append("|---|" + "---|" * (len(configs) + 1))
        for t, v in zip(tasks, vbs_plain, strict=True):
            lines.append(
                f"| {t.split('_')[-1]} | "
                + " | ".join(f"{rate[(t, c)]:.2f}" for c in configs)
                + f" | {v:.2f} |"
            )
        lines += [
            "",
            f"Mean SBS {m_sbs:.3f}; mean VBS {m_plain:.3f}; **gap (plain) {m_plain - m_sbs:.3f}**; "
            f"gap (conservative, > 1 seed) {m_cons - m_sbs:.3f}.",
            "",
            "Tasks where the SBS is not the best configuration "
            f"({len(not_best)} of {len(tasks)}; * = the winner beats the SBS by more than one seed):",
            "",
        ]
        if not_best:
            for t, s_rate, best, winners, strong in not_best:
                lines.append(
                    f"- {t.split('_')[-1]}: SBS {s_rate:.2f}, best {best:.2f} by "
                    f"{', '.join(winners)}{' *' if strong else ''}"
                )
        else:
            lines.append("- none")
        summary.append((model, len(tasks), sbs, m_sbs, m_plain, m_cons))
        pooled["sbs"] += [rate[(t, sbs)] for t in tasks]
        pooled["plain"] += vbs_plain
        pooled["cons"] += vbs_cons
    lines += [
        "",
        "## Overall",
        "",
        "| model | tasks | SBS | mean SBS | mean VBS | gap (plain) | gap (conservative) |",
        "|---|---|---|---|---|---|---|",
    ]
    for model, n, sbs, a, b, c in summary:
        lines.append(f"| {model} | {n} | {sbs} | {a:.3f} | {b:.3f} | {b - a:.3f} | {c - a:.3f} |")
    n_all = len(pooled["sbs"])
    a, b, c = (sum(pooled[k]) / n_all for k in ("sbs", "plain", "cons"))
    lines += [f"| all tasks pooled (each model with its own SBS) | {n_all} | - | {a:.3f} | {b:.3f} | {b - a:.3f} | {c - a:.3f} |",
              "",
              "Different models have different configuration sets (WC has no TPE) and different seed "
              "counts, so the pooled row is a task-weighted summary, not a like-for-like estimate."]  # fmt: skip
    text = "\n".join(lines) + "\n"
    (ROOT / "results/selection_headroom.md").write_text(text)
    return text


if __name__ == "__main__":
    print(main())
